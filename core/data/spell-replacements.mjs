// Объединённые карточки: переносим только избранное, не события и не действующие чары.
// Журнал хранит полную карточку каста и продолжает использовать прежний эффект и цену.
export const SPELL_REPLACEMENTS = Object.freeze({
  M18: 'M06', // Дальняя нить → единая Нить ладоней
  M27: 'M05', // Обезболивание → первая помощь
  M33: 'M15', // Приживление → сильное исцеление
  M40: 'M41', // Звуковой фон → малый морок
  M115: 'M111', // Томление → Приворот
});

export function canonicalFavorites(ids) {
  return [...new Set(ids.filter((id) => typeof id === 'string').map((id) => SPELL_REPLACEMENTS[id] ?? id))];
}
